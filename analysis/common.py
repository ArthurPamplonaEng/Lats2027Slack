def read_csv_numeric(path: str, comment: str = "#") -> tuple[list[str], np.ndarray]:
    with open(path, encoding="utf-8") as f:
        lines = [ln for ln in f if ln.strip() and not ln.startswith(comment)]
    rd = csv.reader(lines)
    hdr = next(rd)
    rows = []
    for r in rd:
        try:
            rows.append([float(x) if x != "" else np.nan for x in r])
        except ValueError:
            continue
    return hdr, np.array(rows, dtype=float)


def read_csv_dicts(path: str, comment: str = "#") -> list[dict]:
    with open(path, encoding="utf-8") as f:
        lines = [ln for ln in f if ln.strip() and not ln.startswith(comment)]
    return list(csv.DictReader(lines))


class Values:
    def __init__(self):
        self.v: dict[str, tuple[object, str]] = {}

    def put(self, name: str, value, fmt: str = "{}"):
        if not name.isalpha():
            raise ValueError(f"macro name must be letters only: {name}")
        self.v[name] = (value, fmt)
        return value

    def tex(self) -> str:
        out = ["% generated by analysis/run_all.py -- do not edit"]
        for k in sorted(self.v):
            val, fmt = self.v[k]
            s = fmt.format(val) if not isinstance(val, str) else val
            s = s.replace("-", "$-$") if s.startswith("-") else s
            out.append(f"\\newcommand{{\\v{k}}}{{{s}}}")
        return "\n".join(out) + "\n"

    def write(self):
        os.makedirs(GEN, exist_ok=True)
        with open(os.path.join(GEN, "values.tex"), "w") as f:
            f.write(self.tex())
        with open(os.path.join(ROOT, "analysis", "results.json"), "w") as f:
            json.dump({k: (v if isinstance(v, (int, float, str)) else str(v))
                       for k, (v, _) in self.v.items()}, f, indent=1, sort_keys=True)


V = Values()


def read_cols(path: str, cols: list[str], comment: str = "#") -> dict[str, np.ndarray]:
    """Selected columns of a CSV with mixed text/number fields (empty or text -> NaN)."""
    with open(path, encoding="utf-8") as f:
        rd = csv.reader(ln for ln in f if ln.strip() and not ln.startswith(comment))
        hdr = next(rd)
        idx = [hdr.index(k) for k in cols]
        out = [[] for _ in cols]
        for r in rd:
            if len(r) < len(hdr):
                continue
            for j, i in enumerate(idx):
                try:
                    out[j].append(float(r[i]))
                except ValueError:
                    out[j].append(np.nan)
    return {k: np.array(v) for k, v in zip(cols, out)}
