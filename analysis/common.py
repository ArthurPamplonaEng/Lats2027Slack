"""Shared constants, loaders and the values registry of the LATS 2027 analysis.

Every number printed in the paper is registered here with `V.put(name, value, fmt)` and written to
paper/generated/values.tex as \\v<name> (and to analysis/results.json). Never type a result into
the .tex by hand.
"""
from __future__ import annotations

import csv
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
FIG = os.path.join(ROOT, "paper", "figures")
GEN = os.path.join(ROOT, "paper", "generated")

